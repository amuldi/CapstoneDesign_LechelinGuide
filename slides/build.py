def set_font(run, name):
    """python-pptx는 latin만 설정합니다. 한글은 ea(동아시아) 글꼴을 따로 지정해야 합니다."""
    rPr = run._r.get_or_add_rPr()
    for tag in ("a:latin", "a:ea", "a:cs"):
        el = rPr.find(qn(tag))
        if el is None:
            el = rPr.makeelement(qn(tag), {})
            rPr.append(el)
        el.set("typeface", name)

