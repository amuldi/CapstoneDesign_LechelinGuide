def box(s, x, y, w, h, text="", size=12, color=INK, bold=False,
        align=PP_ALIGN.LEFT, space=4, anchor=MSO_ANCHOR.TOP, line=1.25):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    for i, ln in enumerate(str(text).split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.space_after = Pt(space)
        p.line_spacing = line
        r = p.add_run(); r.text = ln
        r.font.size, r.font.bold = Pt(size), bold
        r.font.color.rgb = color
        set_font(r, FONT)
    return tb


def rect(s, x, y, w, h, fill=CARD, radius=True):
    from pptx.enum.shapes import MSO_SHAPE
    sh = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE,
                            Inches(x), Inches(y), Inches(w), Inches(h))
    sh.fill.solid(); sh.fill.fore_color.rgb = fill
    sh.line.fill.background()
    sh.shadow.inherit = False
    if radius:
        try: sh.adjustments[0] = 0.06
        except Exception: pass
    return sh


