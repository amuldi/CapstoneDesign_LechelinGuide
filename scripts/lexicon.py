"""한국어 배달 리뷰 항목별 감성 — 규칙 기반.

설계 원칙
 1. 긍정어/부정어 사전을 각각 두고 개수로 판정 (부정어 하나 = 부정 아님)
 2. 한 절에 긍·부정이 섞이면 판단 보류 — 대표 근거로 쓰면 안 되는 문장
 3. 이중부정 중화: "적지 않게" → 긍정
 4. 가정·우려 표현 보류: "부족할까봐", "시키면 부족해서"
 5. 절 단위 판정: "맛있어요! 배달은 최악" → 맛 긍정 + 배달 부정

주의: 부분 문자열 매칭이라 어근을 좁게 잡아야 합니다.
 "느끼"는 "느끼다니"에, "이상"은 "한 번 이상"에, "흘러"는 "흘러넘치는"에 걸립니다.
"""
import re

ASPECTS = {
  "맛":    (r"맛있|맛없|맛은|맛이|맛도|맛만|맛나|맛좋|맛집|풍미|간이|간은|비리|비려|"
            r"짜요|짭|싱겁|느끼하|느끼해|담백|고소|신선|바삭|촉촉|쫄깃|질겨|질김|퍽퍽|"
            r"존맛|꿀맛|딱딱|안\s*익"),
  "양":    (r"양이|양은|양도|양만|푸짐|푸집|넉넉|적어|많아|많고|많네|부족|배부|배\s*터|배터|"
            r"가득|실하|두툼|든든|충분|큼직|알차|풍성|듬뿍|수북|어마어마|어머어마|한개씩|"
            r"이정도\s*양|많이\s*넣|많이\s*들어"),
  "가격":  r"가격|가성비|비싸|저렴|혜자|값|돈값|합리적|할인|돈이\s*아깝|이가격",
  "서비스": (r"친절|불친절|응대|사장님|서비스|요청|챙겨|신경\s*써|사장|누락|빠졌|빠져|"
            r"안\s*왔|안\s*보내|안\s*주|안왔|덜\s*왔|들어주|맞춰주|해\s*주신|실수|"
            r"다른\s*메뉴|잘못\s*왔|잘못\s*보내"),
  "배달":  r"배달|배송|늦게|빨리|빠르|식어|식은|샜|새서|포장|기사|도착|따뜻|차갑|찌그러",
}

POS = (r"맛있|맛나|맛좋|좋아|좋았|좋네|좋습|최고|쵝고|짱|굿|만족|훌륭|깔끔|신선|담백|고소|"
       r"푸짐|넉넉|많아|많고|가득|실하|배부|저렴|가성비|혜자|친절|빨라|빠르|따뜻|바삭|촉촉|"
       r"또\s*시|재주문|단골|추천|강추|감사|잘\s*먹|잘먹|괜찮|존맛|꿀맛|맛집|JMT|jmt|"
       r"행복|감동|대만족|최애|인정|성공|극락|사랑|미쳤|지렸|닉값")

# 어근을 좁게. "느끼하"가 아닌 "느끼"는 "느끼다니"에 걸립니다.
NEG = (r"맛없|별로|별루|최악|실망|아쉽|아쉬|늦게|늦어|늦었|식어|식은|눅눅|비려|비림|"
       r"짜요|짜게|싱겁|느끼하|느끼해|느끼함|불친절|적어|부족|비싸|다신|다시는|구려|"
       r"질겨|질김|퍽퍽|이상하|이상해|이상함|불편|차갑|새서|샜|흘렀|비위|역겨|느글|"
       r"돈이\s*아깝|안\s*시켜|안시켜|먹다\s*버|환불|누락|빠졌|잘못\s*왔|다른\s*메뉴")

# 이중부정: 부정 어근 + "-지 않/못" → 중화
DOUBLE = re.compile(
  r"(적|작|많|늦|비싸|짜|싱겁|느끼|비리|질기|눅눅|차갑|부족|이상하|나쁘)"
  r"(지|지는|지도)\s*(않|안\s)")

# 가정·우려는 실제 불만이 아님
HYPO = re.compile(r"(까\s*봐|까봐|줄\s*알았|려나|걱정|시키면|시켰더니|뻔했|뻔 했)")

# 문장부호 + 역접 연결어미에서 끊습니다. 한국어는 거기서 극성이 뒤집힙니다.
SPLIT = re.compile(r"[.!?~\n…,]+|\s(?:근데|그런데|다만|하지만|대신|단)\s"
                   r"|(?<=[가-힣])(?:은데|는데|지만|으나)\s*")


def clauses(text):
    return [c.strip() for c in SPLIT.split(str(text)) if len(c.strip()) >= 2]


def polarity(clause):
    """절 하나의 극성. 1=긍정, -1=부정, 0=판단 보류."""
    if HYPO.search(clause):
        return 0
    c = DOUBLE.sub("긍정표현", clause)
    p = len(re.findall(POS, c))
    n = len(re.findall(NEG, c))
    if p and n:                 # 한 절에 섞이면 대표 근거로 부적합
        return 0
    if p: return 1
    if n: return -1
    return 0


def analyze(text):
    """리뷰 하나 → {항목: 극성}. 항목이 안 잡히거나 보류면 키가 없습니다."""
    out = {}
    for cl in clauses(text):
        pol = polarity(cl)
        if pol == 0:
            continue
        for a, pat in ASPECTS.items():
            if re.search(pat, cl):
                out.setdefault(a, []).append(pol)
    return {a: (1 if sum(v) > 0 else -1) for a, v in out.items() if sum(v) != 0}


if __name__ == "__main__":
    tests = [
      ("치킨은 너무 맛있었어요! 배달기사는 진짜 최악", {"맛": 1, "배달": -1}),
      ("맛있어요~혼자먹기 좋은 양이고 가성비도 아주 좋아요~!", {"맛": 1, "양": 1, "가격": 1}),
      ("양도 적지 않게 주셔서 여러명이서 잘 먹었어요", {"양": 1}),
      ("맛은 괜찮은데 배달이 너무 늦어요", {"맛": 1, "배달": -1}),
      ("비리지 않고 신선했어요", {"맛": 1}),
      ("사장님이 정말 친절하세요", {"서비스": 1}),
      ("양이 너무 적어요 다신 안 시킬듯", {"양": -1}),
      ("오늘도 흘러넘치는 치즈에 감동, 우리 동네 피자 맛집", {"맛": 1}),
      ("이 맛을 이제야 다시 느끼다니 너무 맛있습니다", {"맛": 1}),
      ("한 달에 최소 한 번 이상은 무조건 주문하게 되는 맛집입니다", {"맛": 1}),
      ("맛은 아쉽지만 양은 많고 좋았어요", {"맛": -1, "양": 1}),
      ("맛있는데 주문한 메뉴와 다른 메뉴가 왔어요", {"맛": 1, "서비스": -1}),
      ("항상 맛있게 먹는데 이번엔 비위 상할 뻔했어요", {}),
      ("하나 시키면 부족해서 두 개 시켰더니 행복해하네요", {}),
    ]
    ok = 0
    for t, want in tests:
        got = analyze(t)
        hit = (got == want) if want == {} else all(got.get(k) == v for k, v in want.items())
        ok += hit
        print(("  OK  " if hit else "  X   ") + t[:48])
        if not hit:
            print("        기대", want, "→ 실제", got)
    print(f"\n{ok}/{len(tests)} 통과")
